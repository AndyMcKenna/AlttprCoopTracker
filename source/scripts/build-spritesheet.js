'use strict';

/**
 * Pack the sprite PNGs into one sheet, with a CSS class per sprite.
 *
 *   node scripts/build-spritesheet.js      (or: npm run build-sprites)
 *
 * The individual files in wwwroot/sprites/items and wwwroot/sprites/checks
 * stay the place sprites are added and edited; this collects them so the
 * board fetches one image instead of one per tile. Run it after adding,
 * removing or redrawing a sprite, and commit sheet.png and sheet.css with
 * the change. CI fails when the sheet is behind its sources.
 *
 * The CSS carries each sprite's position and size as custom properties and
 * one shared rule does the rest: scale the sprite to fit its tile and centre
 * it, the same as object-fit: contain did when every sprite was an <img>.
 * The scaled sprite is drawn by a ::before sized to fit it exactly, so the
 * sprites beside it on the sheet never show through a tile that is wider or
 * taller than the sprite in it.
 */

const crypto = require('crypto');
const fs = require('fs');
const path = require('path');
const { PNG } = require('pngjs');

const SPRITES_DIR = path.join(__dirname, '..', 'AlttpTracker.Api', 'wwwroot', 'sprites');
const KINDS = ['items', 'checks'];
const SHEET_PNG = path.join(SPRITES_DIR, 'sheet.png');
const SHEET_CSS = path.join(SPRITES_DIR, 'sheet.css');

// A transparent border round every sprite, so scaling one never samples the
// pixels of its neighbour. Also keeps the sheet strictly larger than any one
// sprite, which the percentage maths in the CSS relies on.
const GAP = 2;
const MAX_WIDTH = 512;

/** One entry per PNG: its pixels, size, and the class it will get. */
function loadSprites() {
  const sprites = [];
  for (const kind of KINDS) {
    const dir = path.join(SPRITES_DIR, kind);
    const files = fs
      .readdirSync(dir)
      .filter((file) => file.toLowerCase().endsWith('.png'))
      .sort();
    for (const file of files) {
      const png = PNG.sync.read(fs.readFileSync(path.join(dir, file)));
      sprites.push({
        kind,
        name: file.replace(/\.png$/i, ''),
        width: png.width,
        height: png.height,
        data: png.data,
      });
    }
  }
  return sprites;
}

/**
 * Shelf packing: tallest sprites first, laid left to right, starting a new
 * row when one would run past MAX_WIDTH. Not the tightest packing, but the
 * sheet is small and the layout is easy to read in the CSS.
 */
function pack(sprites) {
  const order = [...sprites].sort(
    (a, b) => b.height - a.height || b.width - a.width || a.kind.localeCompare(b.kind) || a.name.localeCompare(b.name)
  );

  let x = GAP;
  let y = GAP;
  let rowHeight = 0;
  let sheetWidth = 0;

  for (const sprite of order) {
    if (x + sprite.width + GAP > MAX_WIDTH && x > GAP) {
      x = GAP;
      y += rowHeight + GAP;
      rowHeight = 0;
    }
    sprite.x = x;
    sprite.y = y;
    x += sprite.width + GAP;
    rowHeight = Math.max(rowHeight, sprite.height);
    sheetWidth = Math.max(sheetWidth, x);
  }

  return { width: sheetWidth, height: y + rowHeight + GAP };
}

function drawSheet(sprites, size) {
  const sheet = new PNG({ width: size.width, height: size.height });
  sheet.data.fill(0);
  for (const sprite of sprites) {
    for (let row = 0; row < sprite.height; row += 1) {
      const from = row * sprite.width * 4;
      const to = ((sprite.y + row) * size.width + sprite.x) * 4;
      sprite.data.copy(sheet.data, to, from, from + sprite.width * 4);
    }
  }
  return PNG.sync.write(sheet);
}

/** A fingerprint of the source pixels, so the CSS changes whenever they do. */
function fingerprint(sprites) {
  const hash = crypto.createHash('sha256');
  for (const sprite of sprites) {
    hash.update(sprite.kind + '/' + sprite.name + ':' + sprite.width + 'x' + sprite.height + '\n');
    hash.update(sprite.data);
  }
  return hash.digest('hex').slice(0, 12);
}

function writeCss(sprites, size, version) {
  const lines = [
    '/* Generated by scripts/build-spritesheet.js from wwwroot/sprites/{items,checks}. Do not edit. */',
    '/* sources: ' + version + ' */',
    '',
    '/* The element is the tile; the sprite is drawn by ::before, sized to exactly',
    '   the scaled sprite and centred, so nothing next to it on the sheet can',
    '   show through the rest of the tile. */',
    '.sprite {',
    '  --sheet-w: ' + size.width + ';',
    '  --sheet-h: ' + size.height + ';',
    '  /* How far to blow the sprite up so it fits its tile, like object-fit: contain. */',
    '  --k: min(var(--tile) / var(--sw), var(--tile) / var(--sh));',
    '  position: relative;',
    '  display: block;',
    '  width: var(--tile);',
    '  height: var(--tile);',
    '}',
    '',
    '.sprite::before {',
    '  content: "";',
    '  position: absolute;',
    '  inset: 0;',
    '  margin: auto;',
    '  width: calc(var(--sw) * var(--k));',
    '  height: calc(var(--sh) * var(--k));',
    '  background-image: url(sheet.png?v=' + version + ');',
    '  background-repeat: no-repeat;',
    '  background-size: calc(var(--sheet-w) * var(--k)) calc(var(--sheet-h) * var(--k));',
    '  background-position: calc(var(--sx) * var(--k) * -1) calc(var(--sy) * var(--k) * -1);',
    '  image-rendering: pixelated;',
    '}',
    '',
  ];
  for (const sprite of sprites) {
    lines.push(
      '.sprite--' + sprite.kind + '-' + sprite.name +
        ' { --sx: ' + sprite.x + '; --sy: ' + sprite.y +
        '; --sw: ' + sprite.width + '; --sh: ' + sprite.height + '; }'
    );
  }
  return lines.join('\n') + '\n';
}

function main() {
  const sprites = loadSprites();
  const size = pack(sprites);
  const version = fingerprint(sprites);

  fs.writeFileSync(SHEET_PNG, drawSheet(sprites, size));
  fs.writeFileSync(SHEET_CSS, writeCss(sprites, size, version));

  console.log(
    sprites.length + ' sprites packed into ' + size.width + 'x' + size.height + ' ' +
      path.relative(process.cwd(), SHEET_PNG) + ' (' + fs.statSync(SHEET_PNG).size + ' bytes), ' +
      path.relative(process.cwd(), SHEET_CSS)
  );
}

if (require.main === module) main();

module.exports = { loadSprites, fingerprint, SHEET_CSS };
